        expect(page.get_by_text('A fictional family asks for professional help.',exact=True)).to_be_visible()

        # The existing-lawyer invitation route converges on the same workspace.
        page.locator('.sidebar .nav-item').filter(has_text='Cases').click()
        page.get_by_role('button',name='New estate case',exact=True).click()
        page.get_by_label('Name of the deceased',exact=True).fill('Invited family estate '+stamp)
        page.get_by_role('button',name='Create case',exact=True).click()
        expect(page.get_by_role('dialog')).not_to_be_visible()
        page.get_by_role('button',name='Invite family',exact=True).click()
        page.get_by_role('dialog').get_by_label('Email address',exact=True).fill('browser'+stamp+'@demo.my')
        page.get_by_label('Case role',exact=True).select_option('true')
        page.get_by_role('button',name='Create invitation',exact=True).click()
        expect(page.get_by_role('dialog',name='Your invitation is ready')).to_be_visible()
        link=page.get_by_label('Invitation link',exact=True).input_value()
        page.get_by_role('button',name='Close dialog',exact=True).click()
        logout()
        page.goto(link,wait_until='networkidle')
        login('browser'+stamp+'@demo.my')
        expect(page.get_by_role('dialog',name='You’ve been invited')).to_be_visible()
        page.get_by_role('button',name='Accept invitation',exact=True).click()
        expect(page.get_by_role('dialog')).not_to_be_visible()
        expect(page.get_by_role('heading',name='Invited family estate '+stamp,exact=True)).to_be_visible()
        assert not errors,errors
        (OUT/'browser-results.json').write_text(json.dumps({'passed':True,'page_errors':errors,'checks':['role login','BM/EN navigation','document privacy','revision upload','task persistence','keyboard dialog dismissal','mobile overflow','reduced motion','legal review','submission','officer query','published query response','resubmission','hearing','order','all asset releases','reconciled completion','public registration and intake','lawyer acceptance retaining facts','existing-lawyer invitation']},indent=2))
        print('Browser walkthrough passed; screenshots in test-results/',flush=True)
        browser.close()

