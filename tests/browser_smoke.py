        # Public intake is independent of the seeded case and preserves drafts.
        page.get_by_role('button',name='Create account',exact=True).first.click()
        stamp=str(int(time.time()))
        page.get_by_label('Full name',exact=True).fill('Demo Family '+stamp)
        page.get_by_label('Email address',exact=True).fill('browser'+stamp+'@demo.my')
