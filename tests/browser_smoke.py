"""Connected role walkthrough and responsive browser checks. Run with both servers up."""
import json
import os
import time
import urllib.request
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = os.getenv('APP_URL', 'http://127.0.0.1:3000')
OUT = Path('test-results')
OUT.mkdir(exist_ok=True)

def run():
    errors=[]
    for attempt in range(30):
        try:
            urllib.request.urlopen(BASE+'/api/health',timeout=2).close()
            break
        except Exception:
            if attempt==29:
                raise RuntimeError('Start the API and frontend before running the browser walkthrough.')
            time.sleep(1)
    with sync_playwright() as p:
        path=os.getenv('CHROMIUM_PATH')
        if not path and not Path(p.chromium.executable_path).exists():
            candidates=sorted((Path.home()/'.cache/ms-playwright').glob('chromium-*/chrome-linux64/chrome'))
            path=str(candidates[-1]) if candidates else None
        browser=p.chromium.launch(headless=True,executable_path=path,args=['--no-sandbox'])
        page=browser.new_page(viewport={'width':1440,'height':1000},reduced_motion='reduce')
        page.on('pageerror',lambda e: errors.append(str(e)))
        page.goto(BASE,wait_until='networkidle',timeout=120000)
        page.locator('.auth-form-wrap').wait_for(timeout=60000)
        print('Login rendered',flush=True)
        page.screenshot(path=str(OUT/'login-desktop.png'),full_page=True)

        def login(email):
            page.get_by_label('Email address',exact=True).fill(email)
            page.get_by_label('Password',exact=True).fill('Demo2026!')
            page.locator('form button[type=submit]').click()
            page.locator('.app-shell').wait_for(timeout=30000)
            page.wait_for_load_state('networkidle')

        def logout():
            page.get_by_role('button',name='Sign out',exact=True).click()
            page.locator('.auth-form-wrap').wait_for()

        login('sarah@demo.my')
        expect(page.get_by_role('heading',name='Good morning, Sarah.')).to_be_visible()
