        page.get_by_role('button',name='Send response',exact=True).click()
        expect(page.get_by_role('dialog')).not_to_be_visible()
        for task_title in ['Respond to agency query','Confirm overseas contact details']:
            row=page.locator('.task-row').filter(has=page.get_by_text(task_title,exact=True))
            row.get_by_role('button',name='Complete review',exact=True).click()
