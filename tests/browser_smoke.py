        expect(page.locator('.sidebar').get_by_role('button',name='Papan pemuka',exact=True)).to_be_visible()
        page.get_by_role('button',name='Change language',exact=True).click()
        page.screenshot(path=str(OUT/'lawyer-dashboard.png'),full_page=True)
        page.get_by_role('button',name='Ahmad bin Abdullah EU-2026-0042').click()
        page.get_by_role('tab',name='People',exact=True).click()
        expect(page.get_by_text('Private professional notes',exact=True)).to_be_visible()
        page.get_by_role('tab',name='Documents',exact=True).click()
        page.get_by_role('button',name='Marriage certificate',exact=False).click()
        page.get_by_role('dialog').wait_for()
        page.screenshot(path=str(OUT/'document-review.png'),full_page=True)
        page.keyboard.press('Escape')
        expect(page.get_by_role('dialog')).not_to_be_visible()
        logout()

        login('aina@demo.my')
        page.get_by_role('button',name='Ahmad bin Abdullah EU-2026-0042').click()
        page.get_by_role('tab',name='Documents',exact=True).click()
        expect(page.get_by_text('farid-identity-demo.txt',exact=False)).not_to_be_visible()
        page.get_by_role('button',name='Marriage certificate',exact=False).click()
        page.get_by_role('button',name='Upload new revision',exact=True).click()
        page.get_by_label('Choose document file').set_input_files({'name':'marriage-clear.txt','mimeType':'text/plain','buffer':b'Fictional clear marriage record. Both names and registration date confirmed.'})
        page.get_by_role('dialog').get_by_role('button',name='Upload document',exact=True).click()
        expect(page.get_by_role('dialog')).not_to_be_visible()
        expect(page.get_by_text('marriage-clear.txt',exact=False)).to_be_visible()
        page.get_by_role('tab',name='My tasks',exact=False).click()
        page.get_by_role('button',name='Respond',exact=True).first.click()
        page.get_by_label('Your response').fill('The clearer document has been uploaded for review.')
        page.get_by_role('button',name='Send response',exact=True).click()
        expect(page.get_by_role('dialog')).not_to_be_visible()
        page.reload(wait_until='networkidle')
        expect(page.get_by_text('The clearer document has been uploaded for review.',exact=False)).to_be_visible()
        page.set_viewport_size({'width':390,'height':844})
        page.emulate_media(reduced_motion='reduce')
        page.get_by_role('tab',name='Overview',exact=True).click()
        page.screenshot(path=str(OUT/'family-mobile.png'),full_page=True)
        if not page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'):
            print('Overflow:',page.evaluate('[...document.querySelectorAll("body *")].filter(e=>e.getBoundingClientRect().right>innerWidth+1).map(e=>({tag:e.tagName,cls:e.className,right:e.getBoundingClientRect().right})).slice(0,15)'),flush=True)
            raise AssertionError('Mobile layout overflows horizontally')
        page.get_by_role('button',name='Open navigation').click()
        logout()
        page.set_viewport_size({'width':1440,'height':1000})

        login('sarah@demo.my')
        page.get_by_role('button',name='Ahmad bin Abdullah EU-2026-0042').click()
        page.get_by_role('tab',name='Documents',exact=True).click()
        page.get_by_role('button',name='marriage-clear.txt',exact=False).click()
        page.get_by_role('button',name='Mark accepted',exact=True).click()
        expect(page.get_by_role('dialog')).not_to_be_visible()
        page.get_by_role('tab',name='Tasks',exact=True).click()
        page.get_by_role('button',name='Complete review',exact=True).first.click()
        page.get_by_role('tab',name='Overview',exact=True).click()
        page.get_by_role('button',name='Complete legal review',exact=True).click()
        page.get_by_role('button',name='Submit application',exact=True).click()
        expect(page.locator('.case-status-line')).to_contain_text('Agency review')
        logout()

        login('daniel@demo.my')
        page.get_by_role('button',name='Ahmad bin Abdullah EU-2026-0042').click()
        page.get_by_role('tab',name='Submitted documents',exact=True).click()
        expect(page.get_by_text('farid-identity-demo.txt',exact=False)).not_to_be_visible()
        page.get_by_role('tab',name='Queries',exact=True).click()
        page.get_by_role('button',name='New query',exact=True).click()
        page.get_by_label('Required correction').fill('Confirm the overseas contact address in the case response.')
        page.get_by_role('button',name='Send query',exact=True).click()
        expect(page.get_by_role('dialog')).not_to_be_visible()
        page.screenshot(path=str(OUT/'officer-query.png'),full_page=True)
        logout()

        login('farid@demo.my')
        page.get_by_role('button',name='Ahmad bin Abdullah EU-2026-0042').click()
        page.get_by_role('tab',name='My tasks',exact=False).click()
        page.get_by_role('button',name='Respond',exact=True).first.click()
        page.get_by_label('Your response').fill('My overseas address and availability have been confirmed with Sarah.')
