        expect(page.get_by_role('dialog')).not_to_be_visible()
        expect(page.get_by_role('heading',name='Simulated distribution order',exact=True)).to_be_visible()
        logout()

        login('sarah@demo.my')
        page.get_by_role('button',name='Ahmad bin Abdullah EU-2026-0042').click()
        page.get_by_role('button',name='Start asset implementation',exact=True).click()
        expect(page.locator('.case-status-line')).to_contain_text('Asset release')
